/** 本機的錯字修正，不需要網路。只換明確有對應且不同的詞。 */
export function fixTerms(text) {
  if (!text) return { text: '', changes: [] };
  let out = text;
  const changes = [];
  for (const [wrong, right] of TERM_FIXES) {
    if (wrong === right) continue;
    if (out.includes(wrong)) {
      out = out.split(wrong).join(right);
      changes.push(`${wrong} → ${right}`);
    }
  }
  return { text: out, changes };
}
